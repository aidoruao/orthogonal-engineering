def save_summary(summary, output_path):
    """
    Save analysis summary to JSON file.
    
    This function writes ONLY to examples/ directory, NOT to repository files.
    
    Args:
        summary: Dictionary of analysis results
        output_path: Path to output JSON file
    """
    # Ensure examples directory exists
    output_dir = Path(output_path).parent
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Create complete summary with metadata
    complete_summary = {
        "analysis_timestamp": datetime.utcnow().isoformat() + "Z",
        "parameter_pair_counts": summary,
        "total_patterns": len(summary),
        "total_occurrences": sum(summary.values()),
        "metadata": {
            "script": "log_analysis_example.py",
            "purpose": "non-destructive pattern detection",
            "safety": "read-only, no repository modifications"
        }
    }
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(complete_summary, f, indent=2)
        
    print(f"[INFO] Summary saved: {output_path}")
    
    # Display summary
    print("\n" + "="*60)
    print("ANALYSIS SUMMARY")
    print("="*60)
    print(f"Total patterns detected: {complete_summary['total_patterns']}")
    print(f"Total occurrences: {complete_summary['total_occurrences']}")
    print("\nTop parameter pairs:")
    
    sorted_pairs = sorted(
        summary.items(),
        key=lambda x: x[1],
        reverse=True
    )
    
    for i, (pair, count) in enumerate(sorted_pairs[:10], 1):
        print(f"  {i}. {pair}: {count} occurrences")
    
    print("="*60)


