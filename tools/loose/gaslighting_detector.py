    def _get_context_window(
        self, lines: List[str], center_index: int, window_size: int = 3
    ) -> List[str]:
        """Get context window around a line"""
        start = max(0, center_index - window_size)
        end = min(len(lines), center_index + window_size + 1)
        return lines[start:end]

    def compare_analysis_methods(
        self, method1_name: str, method1_results: Dict,
        method2_name: str, method2_results: Dict
    ) -> AnalysisDiscrepancy:
        """Compare two analysis methods and record discrepancies"""

        # Extract violation counts
        count1 = method1_results.get("violation_count", 0)
        count2 = method2_results.get("violation_count", 0)

        # Calculate discrepancy
        if count1 == 0 and count2 == 0:
            discrepancy_magnitude = 0.0
        elif count1 == 0 or count2 == 0:
            discrepancy_magnitude = 1.0
        else:
            discrepancy_magnitude = abs(count1 - count2) / max(count1, count2)

        # Determine likely cause
        if discrepancy_magnitude > 0.5:
            if count1 == 1 and count2 > 100:
                likely_cause = "absorption_overwhelm_attack"
            elif count1 > count2 * 10:
                likely_cause = "false_negative_attack"
            elif count2 > count1 * 10:
                likely_cause = "false_positive_attack"
            else:
                likely_cause = "epistemic_corruption"
        else:
            likely_cause = "normal_variance"

        discrepancy = AnalysisDiscrepancy(
            discrepancy_id=f"disc_{hashlib.md5(str(datetime.utcnow()).encode()).hexdigest()[:8]}",
            timestamp=datetime.utcnow().isoformat(),
            analysis_method_1=method1_name,
            analysis_method_2=method2_name,
            result_1=count1,
            result_2=count2,
            discrepancy_magnitude=discrepancy_magnitude,
            evidence_hash=hashlib.sha256(
                f"{method1_name}:{count1}:{method2_name}:{count2}".encode()
            ).hexdigest(),
            likely_cause=likely_cause
        )

        self.discrepancies.append(discrepancy)
        return discrepancy

    def generate_violation_density_map(
        self, violations: List[Dict], file_size: int, sample_size: int = 10000000
    ) -> Dict:
        """Generate violation density visualization data"""

        if not violations:
            return {"error": "No violations provided"}

        # Group violations by approximate location in file
        density_bins = 10
        bin_size = sample_size / density_bins

        density_data = {f"bin_{i}": 0 for i in range(density_bins)}

        for violation in violations:
            line_num = violation.get("line_number", 0)
            # Approximate position in file (assuming uniform line distribution)
            position_ratio = line_num / 1000000  # Rough estimate
            bin_index = min(int(position_ratio * density_bins), density_bins - 1)
            density_data[f"bin_{bin_index}"] += 1

        # Calculate statistics
        total_violations = len(violations)
        max_density = max(density_data.values())
        min_density = min(density_data.values())
        avg_density = total_violations / density_bins

        return {
            "density_bins": density_data,
            "statistics": {
                "total_violations": total_violations,
                "max_density": max_density,
                "min_density": min_density,
                "avg_density": avg_density,
                "density_variance": max_density - min_density,
                "file_size_bytes": file_size,
                "sample_size_bytes": sample_size,
                "violations_per_mb": total_violations / (sample_size / 1000000)
            },
            "visualization_ready": True,
            "generated": datetime.utcnow().isoformat()
        }

