    def _detect_context_separation(
        self, text_block: str, line_numbers: List[int], analysis_context: Dict
    ) -> List[EpistemicCorruptionAlert]:
        """Detect line number misalignments and context separation"""
        alerts = []

        # Check if reported line numbers match actual content
