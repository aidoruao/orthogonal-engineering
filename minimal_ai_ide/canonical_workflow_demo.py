class CanonicalVerifier:
    """Verifies canonical substitutions are correct and unique"""

    def verify_placeholder(self, placeholder: CanonicalPlaceholder) -> Dict[str, Any]:
        """Verify a placeholder has proper canonicalization"""

        verification = {
            "placeholder": placeholder.name,
            "timestamp": datetime.now().isoformat(),
            "checks": [],
            "errors": [],
            "warnings": [],
            "success": False,
        }

        # Check 1: Has equivalence relation
        if placeholder.equivalence_relation is None:
            verification["errors"].append("Missing equivalence relation")
            verification["checks"].append(
                {"check": "equivalence_relation", "passed": False}
            )
        else:
            verification["checks"].append(
                {"check": "equivalence_relation", "passed": True}
            )

        # Check 2: Has canonical selector
        if placeholder.canonical_selector is None:
            verification["errors"].append("Missing canonical selector")
            verification["checks"].append(
                {"check": "canonical_selector", "passed": False}
            )
        else:
            verification["checks"].append(
                {"check": "canonical_selector", "passed": True}
            )

        # Check 3: For theology, must use BIBLICAL_IDENTITY
        if "Jesus" in placeholder.name or "Mediator" in placeholder.name:
            if (
                placeholder.equivalence_relation
                != EquivalenceRelation.BIBLICAL_IDENTITY
            ):
                verification["warnings"].append(
                    f"Theological placeholder should use BIBLICAL_IDENTITY, "
                    f"got {placeholder.equivalence_relation}"
                )

        # Determine success
        verification["success"] = len(verification["errors"]) == 0

        return verification

    def verify_substitution(
        self, original_code: str, substituted_code: str
    ) -> Dict[str, Any]:
        """Verify code substitution is complete"""

        verification = {
            "timestamp": datetime.now().isoformat(),
            "checks": [],
            "success": False,
        }

        # Check: No NotImplementedError in substituted code
        if (
            "NotImplementedError" in substituted_code
            and "CANONICAL PLACEHOLDER" not in substituted_code
        ):
            verification["checks"].append(
                {
                    "check": "no_placeholder_errors",
                    "passed": False,
                    "message": "Code contains NotImplementedError - substitution may be incomplete",
                }
            )
        else:
            verification["checks"].append(
                {"check": "no_placeholder_errors", "passed": True}
            )

        # Check: Contains canonical realization markers
        if "CANONICAL REALIZATION" in substituted_code:
            verification["checks"].append(
                {
                    "check": "has_canonical_markers",
                    "passed": True,
                    "message": "Code contains canonical realization markers",
                }
            )
        else:
            verification["checks"].append(
                {
                    "check": "has_canonical_markers",
                    "passed": False,
                    "message": "Missing canonical realization markers",
                }
            )

        verification["success"] = all(
            check["passed"] for check in verification["checks"]
        )

        return verification


